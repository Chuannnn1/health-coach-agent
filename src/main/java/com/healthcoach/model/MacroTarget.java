package com.healthcoach.model;

public class MacroTarget {
    public int proteinG;
    public int carbsG;
    public int fatG;

    public MacroTarget() {}

    public MacroTarget(int proteinG, int carbsG, int fatG) {
        this.proteinG = proteinG;
        this.carbsG = carbsG;
        this.fatG = fatG;
    }
}
